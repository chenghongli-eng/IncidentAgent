#!/usr/bin/env node
/**
 * Q2（分层归因）的**唯一**词表与判据定义。
 *
 * 为什么单独放一个文件：Q2 这一条判据同时住在四份真值里
 * （仓库内 `ground-truth/F2.json` / `F4.json`，仓库外 `R1.v*` / `R2.v*`）。
 * 四处各写一份，早晚会长歪——而「同一判据在不同批次里口径不一样」，
 * 是这个项目最贵的一类错误（数字与证据表对不上）。
 * 所以词表只在这里定义一次，四份真值都由脚本从这儿取。
 *
 * 判据问的是：**报告有没有把原因分出层？**
 *   · 一组 = 一层。每组是同一层的同义说法。
 *   · 命中组数 ≥ 2 才算分层（写两遍同一个词不算分层，见 score-report.mjs 的 v9→v10 说明）。
 *
 * 两条边界，别越界：
 *   · **排除不是分层**（Q3 的事）：「排除磁盘被写满」没有给原因分配角色。
 *   · **方向不由 Q2 管**（F4-D1 / 发布归因的事）：层级角色指派对不对是另一条判据。
 *
 * 词表里**故意不放**的几个词（都是实测踩出来的）：
 *   · 「根因 / 根本原因」——每份报告都有，是通用词，不是角色标签；
 *   · 裸「放大」——会匹配「放大了告警面」这种非因果用法；
 *   · 裸「前提」——会匹配「不改阈值**的前提下**」这种行文（实测踩到过）；
 *   · 裸「背景」——会匹配「容器重建时刻仅作**背景**」这种行文。
 */
export const Q2_ROLE_GROUPS = [
  {
    name: '触发层',
    pattern:
      '触发源|触发因素|触发条件|触发因|触发原因|直接原因|直接诱因|首因|诱因',
  },
  {
    name: '必要·前提层',
    pattern: '必要条件|必要因素|必要前提|前提条件|前置条件|前置缺陷',
  },
  {
    name: '放大层',
    pattern: '放大条件|放大器|放大因子|放大效应|加剧条件|加剧因素',
  },
  {
    name: '背景·既存层',
    pattern:
      '背景条件|背景风险|背景因素|长期背景|长期条件|既存条件|既有条件|存量条件|基础条件',
  },
];

/**
 * Q2 的完整判据对象（写进真值文件的 `quality` 数组）。
 *
 * 词表里**故意不放**两种词：
 *   · 「根因 / 根本原因」——每份报告都有，是通用词，不是角色标签；
 *   · 裸「放大」——会匹配「放大了告警面」这种非因果用法。
 */
export function q2Check() {
  return {
    id: 'Q2',
    name: '分层归因（至少分出两个不同层级角色）',
    section: 'whole',
    min_groups: {
      n: 2,
      groups: Q2_ROLE_GROUPS,
    },
  };
}
